use std::fs;

use camino::Utf8Path;
use serde::Serialize;
use serde_json::{Map, Value};
use stratum_config::{Config, ProjectConfig};

use stratum_engine::{CONFIG_FILE, config};

const SCHEMA: &str = "https://stratum.dev/schema/v1.json";
const LEADING_KEYS: [&str; 6] = ["id", "path", "files", "severity", "entries", "segments"];

pub fn run(root: &Utf8Path) -> miette::Result<()> {
    let path = root.join(CONFIG_FILE);
    if path.exists() {
        return Err(miette::miette!("{} already exists", path));
    }
    let cfg = config::infer(root);
    let rendered = render_jsonc(&cfg);
    fs::write(&path, rendered).map_err(|e| miette::miette!("Could not write {path}: {e}"))?;
    println!("Wrote {path}");
    Ok(())
}

fn render_jsonc(cfg: &Config) -> String {
    let mut fields = vec![
        ("$schema".to_owned(), inline(&Value::from(SCHEMA))),
        ("version".to_owned(), cfg.version.to_string()),
    ];
    if cfg.project != ProjectConfig::default() {
        fields.push(("project".to_owned(), inline(&to_value(&cfg.project))));
    }
    let structure = match to_value(&cfg.structure) {
        Value::Object(map) => ordered(map)
            .into_iter()
            .map(|(k, v)| (quote(&k), inline(&v)))
            .collect(),
        _ => vec![],
    };
    fields.push(("structure".to_owned(), block('{', '}', &structure)));
    let layers: Vec<String> = cfg.layers.iter().map(|l| inline(&to_value(l))).collect();
    fields.push(("layers".to_owned(), list(&layers)));
    let rules: Vec<(String, String)> = cfg
        .rules
        .iter()
        .map(|(slug, rule)| (quote(slug), inline(&to_value(rule))))
        .collect();
    fields.push(("rules".to_owned(), block('{', '}', &rules)));
    let overrides: Vec<String> = cfg.overrides.iter().map(|o| inline(&to_value(o))).collect();
    fields.push(("overrides".to_owned(), list(&overrides)));

    let body: Vec<(String, String)> = fields.into_iter().map(|(k, v)| (quote(&k), v)).collect();
    format!(
        "// Generated by `stratum-lint init`. Edit me.\n{}\n",
        block_at('{', '}', &body, "")
    )
}

fn to_value(value: &impl Serialize) -> Value {
    let mut value = serde_json::to_value(value).unwrap_or(Value::Null);
    if let Value::Object(map) = &mut value {
        map.retain(|_, v| !v.is_null());
    }
    value
}

fn ordered(map: Map<String, Value>) -> Vec<(String, Value)> {
    let mut pairs: Vec<(String, Value)> = map.into_iter().collect();
    pairs.sort_by_key(|(k, _)| {
        LEADING_KEYS
            .iter()
            .position(|lead| lead == k)
            .unwrap_or(LEADING_KEYS.len())
    });
    pairs
}

fn quote(text: &str) -> String {
    Value::from(text).to_string()
}

fn inline(value: &Value) -> String {
    match value {
        Value::Array(items) => {
            let items: Vec<String> = items.iter().map(inline).collect();
            format!("[{}]", items.join(", "))
        }
        Value::Object(map) if map.is_empty() => "{}".to_owned(),
        Value::Object(map) => {
            let pairs: Vec<String> = ordered(map.clone())
                .into_iter()
                .map(|(k, v)| format!("{}: {}", quote(&k), inline(&v)))
                .collect();
            format!("{{ {} }}", pairs.join(", "))
        }
        scalar => scalar.to_string(),
    }
}

fn list(items: &[String]) -> String {
    let pairs: Vec<(String, String)> = items.iter().map(|i| (String::new(), i.clone())).collect();
    block('[', ']', &pairs)
}

fn block(open: char, close: char, pairs: &[(String, String)]) -> String {
    block_at(open, close, pairs, "  ")
}

fn block_at(open: char, close: char, pairs: &[(String, String)], indent: &str) -> String {
    if pairs.is_empty() {
        return format!("{open}{close}");
    }
    let lines: Vec<String> = pairs
        .iter()
        .map(|(k, v)| {
            if k.is_empty() {
                format!("{indent}  {v}")
            } else {
                format!("{indent}  {k}: {v}")
            }
        })
        .collect();
    format!("{open}\n{}\n{indent}{close}", lines.join(",\n"))
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn rendered_jsonc_round_trips_through_parser() {
        let root = camino::Utf8PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../tests/fixtures/tiny-ts")
            .canonicalize_utf8()
            .unwrap();
        let cfg = config::infer(&root);
        let txt = render_jsonc(&cfg);
        let parsed = stratum_config::parse_str(Utf8Path::new("inline"), &txt).unwrap();
        assert_eq!(parsed, cfg);
    }

    fn sliced_tree() -> (tempfile::TempDir, camino::Utf8PathBuf) {
        let dir = tempfile::tempdir().unwrap();
        let root = camino::Utf8PathBuf::from_path_buf(dir.path().to_path_buf()).unwrap();
        for slice in ["auth", "cart", "profile"] {
            for segment in ["model", "ui"] {
                fs::create_dir_all(root.join(format!("src/features/{slice}/{segment}"))).unwrap();
            }
            fs::write(root.join(format!("src/features/{slice}/index.ts")), "").unwrap();
        }
        fs::create_dir_all(root.join("src/shared/lib")).unwrap();
        (dir, root)
    }

    #[test]
    fn rendered_jsonc_holds_the_full_structure_slices_and_rule_options() {
        let (_dir, root) = sliced_tree();
        let mut cfg = config::infer(&root);
        cfg.rules.get_mut("stratum/no-barrel").unwrap().options =
            serde_json::json!({ "layers": ["shared"] });
        let txt = render_jsonc(&cfg);
        let parsed = stratum_config::parse_str(Utf8Path::new("inline"), &txt).unwrap();
        assert_eq!(parsed, cfg);
        insta::assert_snapshot!(txt);
    }
}
