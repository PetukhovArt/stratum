use std::fs;

use camino::Utf8Path;

use stratum_engine::{CONFIG_FILE, config};

pub fn run(root: &Utf8Path) -> miette::Result<()> {
    let path = root.join(CONFIG_FILE);
    if path.exists() {
        return Err(miette::miette!("{} already exists", path));
    }
    let cfg = config::infer(root);
    let rendered = render_jsonc(&cfg);
    fs::write(&path, rendered).map_err(|e| miette::miette!("Could not write {path}: {e}"))?;
    println!("Wrote {path}");
    Ok(())
}

fn render_jsonc(cfg: &stratum_config::Config) -> String {
    use std::fmt::Write;

    let mut s = String::new();
    s.push_str("// Generated by `stratum-lint init`. Edit me.\n");
    s.push_str("{\n  \"$schema\": \"https://stratum.dev/schema/v1.json\",\n");
    let _ = writeln!(s, "  \"version\": {},", cfg.version);
    let private = serde_json::to_string(&cfg.structure.private).unwrap_or_else(|_| "[]".into());
    let _ = writeln!(s, "  \"structure\": {{ \"private\": {private} }},");
    s.push_str("  \"layers\": [\n");
    for l in &cfg.layers {
        let _ = writeln!(
            s,
            "    {{ \"id\": \"{}\", \"path\": \"{}\", \"depends_on\": [] }},",
            l.id, l.path
        );
    }
    s.push_str("  ],\n  \"rules\": {\n");
    for (slug, rc) in &cfg.rules {
        let _ = writeln!(
            s,
            "    \"{slug}\": {{ \"severity\": \"{}\" }},",
            rc.severity
        );
    }
    s.push_str("  },\n  \"overrides\": []\n}\n");
    s
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;

    #[test]
    fn rendered_jsonc_round_trips_through_parser() {
        let root = camino::Utf8PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../../tests/fixtures/tiny-ts")
            .canonicalize_utf8()
            .unwrap();
        let cfg = config::infer(&root);
        let txt = render_jsonc(&cfg);
        let parsed = stratum_config::parse_str(Utf8Path::new("inline"), &txt).unwrap();
        assert_eq!(parsed, cfg);
    }
}
